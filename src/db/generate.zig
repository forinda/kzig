//! `kzig db generate`: a migration folder written from the schema, as
//! kick/db's `kick db generate` writes one: up/down SQL from a diff against
//! the latest snapshot, the new snapshot, meta.json and the journal entry.
const std = @import("std");
const snap = @import("snapshot.zig");
const diff = @import("diff.zig");
const emit_pg = @import("emit_pg.zig");
const migrate = @import("migrate.zig");
const Timestamp = @import("timestamp.zig").Timestamp;

const Io = std.Io;
const Allocator = std.mem.Allocator;
const Snapshot = snap.Snapshot;

pub const Options = struct {
    /// The migration's name: the id's tail and the journal's tag.
    name: []const u8,
    now: Timestamp,
    hints: diff.Hints = .{},
    /// kick/db's `--empty`: SQL to write by hand, the latest snapshot kept.
    empty: bool = false,
    /// In the banner: `-- Generated by kzig v<version>`.
    version: []const u8 = "dev",
};

pub const Result = struct {
    /// The folder written, or null when the schema hasn't changed.
    id: ?[]const u8,
    changes: []const diff.Change,
};

pub const Latest = struct { snapshot: Snapshot, id: ?[]const u8 };

/// The newest migration's snapshot (kick/db's `readLatestSnapshotEntry`);
/// empty when there is none.
pub fn latest(io: Io, a: Allocator, dir_path: []const u8) !Latest {
    var dir = Io.Dir.cwd().openDir(io, dir_path, .{ .iterate = true }) catch |err| switch (err) {
        error.FileNotFound => return .{ .snapshot = .{}, .id = null },
        else => return err,
    };
    defer dir.close(io);
    var newest: ?[]const u8 = null;
    var it = dir.iterate();
    while (try it.next(io)) |entry| {
        if (entry.kind != .directory or !isId(entry.name)) continue;
        if (newest == null or std.mem.order(u8, entry.name, newest.?) == .gt) newest = try a.dupe(u8, entry.name);
    }
    const id = newest orelse return .{ .snapshot = .{}, .id = null };
    const text = try dir.readFileAlloc(io, try std.fs.path.join(a, &.{ id, "snapshot.json" }), a, .limited(64 << 20));
    return .{ .snapshot = try snap.parse(a, std.mem.trimEnd(u8, text, "\n")), .id = id };
}

/// `YYYYMMDD_HHMMSS_…`
fn isId(name: []const u8) bool {
    if (name.len < 16 or name[8] != '_' or name[15] != '_') return false;
    for (name[0..8]) |c| if (!std.ascii.isDigit(c)) return false;
    for (name[9..15]) |c| if (!std.ascii.isDigit(c)) return false;
    return true;
}

/// Diff `target` against the latest snapshot in `dir_path` and write the
/// migration; nothing when nothing changed.
pub fn run(io: Io, a: Allocator, dir_path: []const u8, target: Snapshot, o: Options) !Result {
    const prev = try latest(io, a, dir_path);
    if (o.empty) {
        const id = try write(io, a, dir_path, prev.snapshot, prev.id, "", "", false, o);
        return .{ .id = id, .changes = &.{} };
    }
    const changes = try diff.diff(a, prev.snapshot, target, o.hints);
    if (changes.len == 0) return .{ .id = null, .changes = changes };
    const up = try emit_pg.emit(a, changes);
    const down = try emit_pg.emit(a, try diff.invert(a, changes));
    // kick/db's relations aren't modelled yet: keep the ones on record.
    var next = target;
    if (next.relations == null) next.relations = prev.snapshot.relations;
    const id = try write(io, a, dir_path, next, prev.id, up, down, diff.hasAmbiguousReverse(changes), o);
    return .{ .id = id, .changes = changes };
}

fn write(io: Io, a: Allocator, dir_path: []const u8, target: Snapshot, previous: ?[]const u8, up_body: []const u8, down_body: []const u8, draft: bool, o: Options) ![]const u8 {
    var iso_buf: [32]u8 = undefined;
    const iso = try std.fmt.bufPrint(&iso_buf, "{f}", .{o.now});
    const id = try std.fmt.allocPrint(a, "{s}{s}{s}_{s}{s}{s}_{s}", .{ iso[0..4], iso[5..7], iso[8..10], iso[11..13], iso[14..16], iso[17..19], o.name });
    const created = try jsonString(a, o.now);
    const cwd = Io.Dir.cwd();
    const folder = try std.fs.path.join(a, &.{ dir_path, id });
    try cwd.createDirPath(io, folder);

    const banner = try std.fmt.allocPrint(a, "-- Generated by kzig v{s} — review state lives in meta.json\n", .{o.version});
    const up = try std.mem.concat(a, u8, &.{
        banner,
        if (o.empty) "-- Empty migration — author SQL below (data migration, seed, etc).\n" else "",
        up_body,
        if (up_body.len > 0) "\n" else "",
    });
    const down = try std.mem.concat(a, u8, &.{
        banner,
        if (draft) "-- DRAFT: ambiguous reverses present (drop column / drop table / type change). Audit before applying.\n" else "",
        if (o.empty) "-- Empty migration — author the reverse SQL here.\n" else "",
        down_body,
        if (down_body.len > 0) "\n" else "",
    });
    const snapshot = try std.mem.concat(a, u8, &.{ try snap.toJson(a, target), "\n" });
    try cwd.writeFile(io, .{ .sub_path = try std.fs.path.join(a, &.{ folder, "up.sql" }), .data = up });
    try cwd.writeFile(io, .{ .sub_path = try std.fs.path.join(a, &.{ folder, "down.sql" }), .data = down });
    try cwd.writeFile(io, .{ .sub_path = try std.fs.path.join(a, &.{ folder, "snapshot.json" }), .data = snapshot });

    var meta: std.json.ObjectMap = .empty;
    try meta.put(a, "id", .{ .string = id });
    try meta.put(a, "name", .{ .string = o.name });
    try meta.put(a, "createdAt", .{ .string = created });
    try meta.put(a, "reviewed", .{ .bool = false });
    try meta.put(a, "dialect", .{ .string = "postgres" });
    try meta.put(a, "previousId", if (previous) |p| .{ .string = p } else .null);
    try meta.put(a, "downIsDraft", .{ .bool = draft });
    try meta.put(a, "empty", .{ .bool = o.empty });
    try cwd.writeFile(io, .{ .sub_path = try std.fs.path.join(a, &.{ folder, "meta.json" }), .data = try pretty(a, .{ .object = meta }) });

    // kick/db's `_journal.json`: one entry per generated migration.
    const journal_path = try std.fs.path.join(a, &.{ dir_path, "_journal.json" });
    var journal: std.json.Value = blk: {
        const text = cwd.readFileAlloc(io, journal_path, a, .limited(16 << 20)) catch |err| switch (err) {
            error.FileNotFound => {
                var j: std.json.ObjectMap = .empty;
                try j.put(a, "version", .{ .integer = 1 });
                try j.put(a, "dialect", .{ .string = "postgres" });
                try j.put(a, "entries", .{ .array = .init(a) });
                break :blk .{ .object = j };
            },
            else => return err,
        };
        break :blk std.json.parseFromSliceLeaky(std.json.Value, a, text, .{}) catch return error.InvalidJournal;
    };
    if (journal != .object) return error.InvalidJournal;
    const entries = journal.object.getPtr("entries") orelse return error.InvalidJournal;
    if (entries.* != .array) return error.InvalidJournal;
    var entry: std.json.ObjectMap = .empty;
    try entry.put(a, "id", .{ .string = id });
    try entry.put(a, "tag", .{ .string = o.name });
    try entry.put(a, "hash", .{ .string = try a.dupe(u8, &migrate.hashOf(up, down, snapshot)) });
    try entry.put(a, "createdAt", .{ .string = created });
    try entries.array.append(.{ .object = entry });
    try cwd.writeFile(io, .{ .sub_path = journal_path, .data = try pretty(a, journal) });
    return id;
}

fn jsonString(a: Allocator, t: Timestamp) ![]const u8 {
    const quoted = try std.json.Stringify.valueAlloc(a, t, .{});
    return quoted[1 .. quoted.len - 1];
}

fn pretty(a: Allocator, v: std.json.Value) ![]const u8 {
    return std.mem.concat(a, u8, &.{ try std.json.Stringify.valueAlloc(a, v, .{ .whitespace = .indent_2 }), "\n" });
}

const testing = std.testing;

const TmpDir = struct {
    tmp: std.testing.TmpDir,
    path: []const u8,

    fn init(a: Allocator) !TmpDir {
        const tmp = std.testing.tmpDir(.{});
        return .{ .tmp = tmp, .path = try std.fmt.allocPrint(a, ".zig-cache/tmp/{s}/migrations", .{tmp.sub_path}) };
    }

    fn read(t: TmpDir, a: Allocator, sub: []const u8) ![]const u8 {
        return std.Io.Dir.cwd().readFileAlloc(testing.io, try std.fs.path.join(a, &.{ t.path, sub }), a, .limited(1 << 20));
    }
};

fn col(name: []const u8, sql_type: []const u8, nullable: bool) snap.Column {
    return .{ .key = name, .name = name, .sql_type = sql_type, .nullable = nullable, .default = null, .default_sql = false, .primary_key = false };
}

const id_col: snap.Column = .{ .key = "id", .name = "id", .sql_type = "serial", .nullable = false, .default = null, .default_sql = false, .primary_key = true };

fn users(a: Allocator, columns: []const snap.Column) !Snapshot {
    const tables = try a.alloc(snap.Table, 1);
    tables[0] = .{ .name = "users", .columns = try a.dupe(snap.Column, columns), .indexes = &.{}, .foreign_keys = &.{}, .checks = &.{}, .primary_key = null };
    return .{ .tables = tables };
}

const t0: Timestamp = .{ .us = 1793102400123000 }; // 2026-10-27T12:00:00.123Z

test "generate: the first migration, its meta and journal entry; nothing changed, nothing written" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var dir = try TmpDir.init(a);
    defer dir.tmp.cleanup();
    const target = try users(a, &.{ id_col, col("email", "text", false) });

    const r = try run(testing.io, a, dir.path, target, .{ .name = "init", .now = t0, .version = "0.2.0" });
    try testing.expectEqualStrings("20261027_120000_init", r.id.?);
    try testing.expectEqualStrings(
        \\-- Generated by kzig v0.2.0 — review state lives in meta.json
        \\CREATE TABLE "users" (
        \\  "id" serial NOT NULL,
        \\  "email" text NOT NULL,
        \\  PRIMARY KEY ("id")
        \\);
        \\
    , try dir.read(a, "20261027_120000_init/up.sql"));
    try testing.expectEqualStrings("-- Generated by kzig v0.2.0 — review state lives in meta.json\nDROP TABLE \"users\";\n", try dir.read(a, "20261027_120000_init/down.sql"));
    try testing.expectEqualStrings(try std.fmt.allocPrint(a, "{s}\n", .{try snap.toJson(a, target)}), try dir.read(a, "20261027_120000_init/snapshot.json"));
    try testing.expectEqualStrings(
        \\{
        \\  "id": "20261027_120000_init",
        \\  "name": "init",
        \\  "createdAt": "2026-10-27T12:00:00.123Z",
        \\  "reviewed": false,
        \\  "dialect": "postgres",
        \\  "previousId": null,
        \\  "downIsDraft": false,
        \\  "empty": false
        \\}
        \\
    , try dir.read(a, "20261027_120000_init/meta.json"));
    // The journal's hash is the one `kzig db migrate` records.
    const list = try migrate.load(testing.io, a, dir.path);
    try testing.expectEqualStrings(try std.fmt.allocPrint(a,
        \\{{
        \\  "version": 1,
        \\  "dialect": "postgres",
        \\  "entries": [
        \\    {{
        \\      "id": "20261027_120000_init",
        \\      "tag": "init",
        \\      "hash": "{s}",
        \\      "createdAt": "2026-10-27T12:00:00.123Z"
        \\    }}
        \\  ]
        \\}}
        \\
    , .{list[0].hash}), try dir.read(a, "_journal.json"));

    const again = try run(testing.io, a, dir.path, target, .{ .name = "noop", .now = t0 });
    try testing.expectEqual(null, again.id);
    try testing.expectEqual(0, again.changes.len);
}

test "generate: a later migration diffs against the latest snapshot; drops make down a draft" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var dir = try TmpDir.init(a);
    defer dir.tmp.cleanup();
    _ = try run(testing.io, a, dir.path, try users(a, &.{id_col}), .{ .name = "init", .now = t0 });
    const r = try run(testing.io, a, dir.path, try users(a, &.{ id_col, col("age", "integer", true) }), .{ .name = "add_age", .now = .{ .us = t0.us + 61_000_000 } });
    try testing.expectEqualStrings("20261027_120101_add_age", r.id.?);
    try testing.expect(std.mem.endsWith(u8, try dir.read(a, "20261027_120101_add_age/up.sql"), "\nALTER TABLE \"users\" ADD COLUMN \"age\" integer;\n"));
    try testing.expect(std.mem.find(u8, try dir.read(a, "20261027_120101_add_age/meta.json"), "\"previousId\": \"20261027_120000_init\"") != null);
    const back = try run(testing.io, a, dir.path, try users(a, &.{id_col}), .{ .name = "drop_age", .now = .{ .us = t0.us + 122_000_000 } });
    const down = try dir.read(a, try std.fmt.allocPrint(a, "{s}/down.sql", .{back.id.?}));
    try testing.expect(std.mem.find(u8, down, "-- DRAFT: ambiguous reverses present (drop column / drop table / type change). Audit before applying.\n") != null);
    try testing.expectEqual(3, (try migrate.load(testing.io, a, dir.path)).len);
}

test "generate: relations in the latest snapshot are carried into the next; a broken journal is an error" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var dir = try TmpDir.init(a);
    defer dir.tmp.cleanup();
    var first = try users(a, &.{id_col});
    var rel: std.json.ObjectMap = .empty;
    try rel.put(a, "users", .{ .object = .empty });
    first.relations = .{ .object = rel };
    _ = try run(testing.io, a, dir.path, first, .{ .name = "init", .now = t0 });
    const r = try run(testing.io, a, dir.path, try users(a, &.{ id_col, col("x", "text", true) }), .{ .name = "x", .now = .{ .us = t0.us + 1_000_000 } });
    const written = try snap.parse(a, std.mem.trimEnd(u8, try dir.read(a, try std.fmt.allocPrint(a, "{s}/snapshot.json", .{r.id.?})), "\n"));
    try testing.expect(written.relations != null);
    try std.Io.Dir.cwd().writeFile(testing.io, .{ .sub_path = try std.fs.path.join(a, &.{ dir.path, "_journal.json" }), .data = "[]" });
    try testing.expectError(error.InvalidJournal, run(testing.io, a, dir.path, try users(a, &.{ id_col, col("y", "text", true) }), .{ .name = "y", .now = .{ .us = t0.us + 2_000_000 } }));
}

test "generate: --empty writes a shell carrying the latest snapshot" {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();
    const a = arena.allocator();
    var dir = try TmpDir.init(a);
    defer dir.tmp.cleanup();
    const first = try run(testing.io, a, dir.path, try users(a, &.{id_col}), .{ .name = "init", .now = t0 });
    const r = try run(testing.io, a, dir.path, try users(a, &.{ id_col, col("x", "text", true) }), .{ .name = "seed", .now = .{ .us = t0.us + 1_000_000 }, .empty = true });
    const up = try dir.read(a, try std.fmt.allocPrint(a, "{s}/up.sql", .{r.id.?}));
    try testing.expect(std.mem.endsWith(u8, up, "\n-- Empty migration — author SQL below (data migration, seed, etc).\n"));
    try testing.expectEqualStrings(
        try dir.read(a, try std.fmt.allocPrint(a, "{s}/snapshot.json", .{first.id.?})),
        try dir.read(a, try std.fmt.allocPrint(a, "{s}/snapshot.json", .{r.id.?})),
    );
    try testing.expect(std.mem.find(u8, try dir.read(a, try std.fmt.allocPrint(a, "{s}/meta.json", .{r.id.?})), "\"empty\": true") != null);
}
